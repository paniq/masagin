#include "util/scanner.hpp"

void bWritePackFile(const sChar *packfilename, const sChar *deffilename)
{
  sVERIFY(packfilename);
  sVERIFY(deffilename);

  // make file list
  sScanner *scan = new sScanner;
  scan->Init();
  scan->DefaultTokens();
  scan->StartFile(deffilename);

  sArray<sPoolString> names;

  while (!scan->Errors && scan->Token!=sTOK_END)
  {
    sPoolString fn;

    // todo: compression flags, etc.

    scan->ScanString(fn);
    if (!scan->Errors)
      if (!sFind(names,fn))
        names.AddTail(fn);
  }

  sInt e=scan->Errors;
  delete scan;
  if (e) return;

  sInt fc=names.GetCount();

  sFile *file = sCreateFile(packfilename,sFA_WRITE);
  if (!file) return;

  bSimplePackFile::Header hdr;
  hdr.Tag=bSimplePackFile::TAG;
  hdr.Version=bSimplePackFile::VERSION;
  hdr.FileCount=fc;
  file->Write(&hdr,sizeof(hdr));

  sS64 diroffs = file->GetOffset();
  bSimplePackFile::DirEntry *dir = new bSimplePackFile::DirEntry[fc];
  sSetMem(dir,0,fc*sizeof(bSimplePackFile::DirEntry));

  file->Write(dir,fc*sizeof(bSimplePackFile::DirEntry));

  for (sInt i=0; i<fc; i++)
  {
    bSimplePackFile::DirEntry &e=dir[i];
    e.Hash=HashName(names[i]);
    for (sInt j=0; j<i; j++)
      if (e.Hash==dir[j].Hash)
      {
        sPrintF(L"ERROR: Hash collision between '%s' and '%s'\n",names[i],names[j]);
        delete dir;
        delete file;
        return;
      }

    sFile *orig = sCreateFile(names[i]);
    if (orig)
    {
      e.Compression=0; // for now ;)
      e.Offset=file->GetOffset();
      e.OriginalSize=e.PackedSize=orig->GetSize();

      // copy (this could be better, but who cares about these few megabytes)
      sU8 *mem=orig->MapAll();
      file->Write(mem,e.PackedSize);
      delete orig;
    }
    else
      sPrintF(L"WARNING: file '%s' not found\n",names[i]);
  }

  // sort directory by hash
  for (sInt i=0; i<fc; i++) 
    for (sInt j=i+1; j<fc; j++)
      if (dir[i].Hash>dir[j].Hash)
        sSwap(dir[i],dir[j]);

  // now write directory and exit
  sInt offs=file->GetOffset();
  file->SetOffset(diroffs);
  file->Write(dir,fc*sizeof(bSimplePackFile::DirEntry));
  file->SetOffset(offs);

  delete dir;
  delete file;
}
