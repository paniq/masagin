// bob's simple pack file. Nice for demos or other two-figure MB sizes

class bFileLogger;

namespace bob
{

  // case insensitive non-unicode string hash function
  static sU32 HashName(const sChar *name)
  {
  	sU32 hash = 5381;
    while (*name)
    {
      sInt c=((*name++)&0xff)|0x20;
      hash = ((hash << 5) + hash) + c;
    }
    return hash;
  }

  static void FixEndian32(void *ptr, sInt bytes)
  {
#if sCONFIG_BE
    sU32 *p32=(sU32*)ptr;
    bytes/=4;
    for (sInt i=0; i<bytes; i++)
      p32[i]=sSwapEndian(p32[i]);
#endif
  }

  static sArray<bFileLogger *> UsedHandlers;

}

using namespace bob;

class bSimplePackFile : public sFileHandler
{
public:

  static const sU32 TAG='BFPF';
  static const sU32 VERSION=1;

  struct Header
  {
    sU32 Tag;
    sU32 Version;
    sU32 FileCount;
  };

  struct DirEntry
  {
    sU32 Hash;
    sU32 Compression;
    sU32 Offset;
    sU32 PackedSize;
    sU32 OriginalSize;
  };

  sFile *File;
  Header *Hdr;
  DirEntry *Dir;

  const sU8 *Mem;
  sU32 Size;

  void Open()
  {
    const sInt hs=sizeof(Header);
    if (Size<hs) goto err;

    Hdr=(Header*)Mem;
    if (Hdr->Tag!=TAG) goto err;
    if (Hdr->Version>VERSION) goto err;

    if (Size<hs+(Hdr->FileCount*sizeof(DirEntry))) goto err;

    Dir = (DirEntry*)(Mem+hs);

    sDPrintF(L"[pf] opened, %d files\n",Hdr->FileCount);
    return;

err:
    Dir=0;
    Mem=0;
    return;   
  }


  bSimplePackFile(const sU8 *mem, sInt size)
  {
    File=0;
    Mem=mem;
    Size=size;
    Open();
  }

  explicit bSimplePackFile(const sChar *filename)
  {
    Mem=0;
    File=sCreateFile(filename);
    if (!File) return;

    Size=File->GetSize();
    Mem=File->MapAll();
    Open();
  }

  ~bSimplePackFile()
  {
    sDelete(File);
  }


  sInt Find(const sChar *name)
  {
    if (!File || !Dir) return -1;
      
    sU32 hash=HashName(name);

    // binary search
    sInt a=0;
    sInt b=Hdr->FileCount;
    while (a<b)
    {
      sInt mid=(a+b)>>1;
      sU32 he=Dir[mid].Hash;
      if (hash==he) return mid;
      if (hash<he) 
        b=mid;
      else
        a=mid+1;
    }
    return -1;
  }


  sBool Exists(const sChar *name)
  {
    sInt n=Find(name);
    return (n>=0);
  }


  sFile *Create(const sChar *name,sFileAccess access)
  {
    if (access!=sFA_READ && access!=sFA_READRANDOM)
    {
      sDPrintF(L"[pf] ERROR: can't open files for writing\n");
      return 0;
    }

    sInt n=Find(name);
    if (n<0) return 0;

    const DirEntry &e=Dir[n];

    if (!e.Offset)
    {
      sDPrintF(L"[pf] ERROR: file '%s' wasn't found at packfile creation\n");
      return 0;
    }

    if (!e.Compression)
    {
      sDPrintF(L"[pf] opening '%s' (%d)\n",name,e.PackedSize);
      return sCreateMemFile(Mem+e.Offset,e.PackedSize,sFALSE);
    }

    sDPrintF(L"[pf] opening '%s' (%d->%d)\n",name,e.PackedSize,e.OriginalSize);

    // packers yet to implement... ;)
    sVERIFYFALSE;

    return 0;
  }

};

void bAddPackFile(const sChar *packfile)
{
  sFileHandler *h=new bSimplePackFile(packfile);
  sAddFileHandler(h);
}

void bAddPackFile(const sU8 *mem, sInt size)
{
  sFileHandler *h=new bSimplePackFile(mem,size);
  sAddFileHandler(h);
}

