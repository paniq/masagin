sBasicPainter::sBasicPainter()
{
  Geo = new sGeometry;
#if sCONFIG_QUADRICS
  Geo->Init(sGF_QUADRICS,sVertexFormatSingle);
#else
  Geo->Init(sGF_QUADLIST,sVertexFormatSingle);
#endif
  GeoX = new sGeometry;
  GeoX->Init(sGF_QUADLIST,sVertexFormatSingle);

  {
    const sInt tx = 128;
    const sInt ty = 128;

#if sRENDERER==sRENDER_PS3GL
    sU32 col0 = sSwapIfBE(0x00ffffff); // ps3 needs swap!
    sU32 col1 = sSwapIfBE(0xffffffff);
#else
    sU32 col0 = 0x00ffffff;
    sU32 col1 = 0xffffffff;
#endif

    sU32 *data = 0;
    {
      sScopeMemSeg seg(sMEMSEG_HEAP);
      data = new sU32[tx*ty];
    }
    for(sInt y=0;y<16;y++)
    {
      for(sInt x=0;x<16;x++)
      {
        for(sInt i=0;i<8;i++)
        {
          sInt bits = sFontData[(y*16+x)*8+i];
          for(sInt j=0;j<8;j++)
          {
            data[(y*8+i)*128+x*8+j] = (bits&0x80) ? col1 : col0;
            bits = bits*2;
          }
        }
      }
    }

    Tex = new sTexture2D(tx,ty,sTEX_ARGB8888|sTEX_2D,1);
    Tex->LoadAllMipmaps((sU8 *)data);
    delete[] data;
  }

  sSimpleMaterial *mtrl;

  mtrl = new sSimpleMaterial;
  mtrl->InitVariants(2);
  mtrl->Texture[0] = Tex;
  mtrl->TFlags[0] = sMTF_LEVEL0;
  mtrl->Flags = sMTRL_ZOFF|sMTRL_CULLOFF|sMTRL_VC_COLOR0;
  mtrl->BlendColor = sMB_OFF;
  mtrl->SetVariant(1);
  mtrl->BlendColor = sMB_ALPHA;
  mtrl->SetVariant(0);
  mtrl->Prepare(sVertexFormatSingle);
  Mtrl = mtrl;

  Env = new sMaterialEnv;
  Env->Fix();

#if !sCONFIG_QUADRICS
  Alloc = 20000;                           // :kludge: shamada: increased this value from
                                            //  10000 to 20000 to be able to have more debug
                                            //  graphs. decrease this for memory optimizing!
  Used = 0;
  Vertices = new sVertexSingle[Alloc*4];
#endif

  View = new sViewport;
  View->Orthogonal = sVO_PIXELS;
  View->CenterX = 0;
  View->CenterY = 0;
  View->Prepare();
}

sBasicPainter::~sBasicPainter()
{
  delete Mtrl;
  delete Geo;
  delete GeoX;
  delete Tex;
  delete Env;
  delete View;
#if !sCONFIG_QUADRICS
  delete[] Vertices;
#endif
}

void sBasicPainter::SetTarget(const sRect &target)
{
  View->SetTarget(0);
  View->Target = target;
  View->Prepare();
}

void sBasicPainter::SetTarget()
{
  View->SetTargetCurrent();
  View->Prepare();
}

void sBasicPainter::Begin()
{
#if sCONFIG_QUADRICS
  Geo->BeginQuadrics();
#else
  Used = 0;
#endif
}

void sBasicPainter::End()
{
 #if sCONFIG_QUADRICS
  sCBuffer<sSimpleMaterialPara> cb;
  View->Set();
  cb.Data->Set();
  Mtrl->Set(&cb);
  Geo->EndQuadrics();
  Geo->Draw();
#else
  sVertexSingle *vp;
  sVERIFY(Used<=Alloc);
  if(Used>0)
  {
    sCBuffer<sSimpleMaterialPara> cb;
    View->Set();
    cb.Data->Set();
    Mtrl->Set(&cb);

    Geo->BeginLoadVB(Used*4,sGD_STREAM,(void**)&vp);
    sCopyMem(vp,Vertices,sizeof(sVertexSingle)*4*Used);
    Geo->EndLoadVB();
    Geo->Draw();
  }
#endif
}

