sPainter::sPainter()
{
  FontId = 0;
  TextColor = ~0;
  Zoom = 1.0f;
}


void sPainter::Box(const sFRect &r,sU32 col)
{
  sU32 cols[4];
  cols[0] = col;
  cols[1] = col;
  cols[2] = col;
  cols[3] = col;

  sBasicPainter::Box(r,cols);
}

void sPainter::Box(sF32 x0,sF32 y0,sF32 x1,sF32 y1,sU32 col)
{
  Box(sFRect(x0,y0,x1,y1),col);
}


void sPainter::SetPrint(sInt fontid,sU32 col,sF32 zoom)
{
  FontId = fontid;
  TextColor = col;
  Zoom = zoom;
}

void sPainter::Print0(sF32 x,sF32 y,const sChar *txt)
{
  Print(FontId,x,y,TextColor,txt,-1,Zoom);
}

